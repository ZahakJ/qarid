/**
 * `name_key` form — `normalizeArabic` of each display name above. This is what
 * `build.ts` looks a شاعر up by; nothing downstream should re-normalise.
 */
export const FAMOUS_POET_KEYS: ReadonlySet<string> = new Set(
  FAMOUS_POET_NAMES.map((n) => normalizeArabic(n)),
)

/** Accepts either a raw `poet name` or an already-normalised `name_key`. */
export function isFamousPoet(name: string | null | undefined): boolean {
  if (!name) return false
  return FAMOUS_POET_KEYS.has(normalizeArabic(name))
}
